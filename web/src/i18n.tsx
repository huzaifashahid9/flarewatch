export const LangContext = createContext<Lang>("en");

export const useLang = () => useContext(LangContext);

// The app shell owns the language; pages read it with useLang and change it with useSetLang.
export const SetLangContext = createContext<(l: Lang) => void>(() => {});
export const useSetLang = () => useContext(SetLangContext);

export function useT() {
  const lang = useContext(LangContext);
  return (key: string, vars: Record<string, string | number> = {}) => {
    let s = lang === "ur" ? UR[key] ?? key : key;
    // In Urdu, isolate numbers and Latin text so "$18.4" or "1.2 to 3.4" keep their order.
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, lang === "ur" ? `\u2066${v}\u2069` : String(v));
    return s;
  };
}
